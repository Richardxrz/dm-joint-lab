/**
 * @file config.h
 * 解决什么：全项目静态容量的唯一定义处（编译期常量，无 malloc）
 * 不解决什么：实际用几路总线 / 几台设备（那是 app 调几次 Create 的事）；预算公式的推导
 * 判据在哪：tests/host/main.c 的容量耗尽用例；公式与合理区间见 docs/工程规范.md §十三
 */
#ifndef SDK_CONFIG_H
#define SDK_CONFIG_H

/**
 * CAN 总线对象池容量。
 * 怎么选：= 板子上物理 FDCAN 的个数（MC02 有 3 个）。多给没有对象可创建，少给浪费硬件。
 * 满了：第 4 次 Bus_Create() 返回 SDK_RS_NO_RESOURCE。
 */
#define SDK_MAX_BUS 3u

/**
 * 每条总线的订阅条数（一个"帧 ID + 回调 + 身份"算一条）。
 * 怎么选：六轴共用 MST_ID 时，"每台接收设备一条"（6 条），再加电容/IMU/上位机。
 * 满了：Bus_Subscribe() 返回 SDK_RS_NO_RESOURCE（不会静默丢一台）。
 */
#define SDK_MAX_SUB 16u

/**
 * 设备对象数。多通道设备算一个（C620 四通道 = 1 个设备）。
 * 怎么选：关节数 + 外设组数 + 1 个预留。
 */
#define SDK_MAX_DEV 8u

/**
 * 周期任务数（Sched 的任务表）。
 * 怎么选：控制 / 下发 / 保护巡检 / 上报 / 遥测 各一条 = 5~6，取 8。
 */
#define SDK_MAX_TASK 8u

/* ===== WHY（维护者面：为什么是这些数，消费者不用读） =====
 *
 * 【定位】只做机械臂这一档（D1/D10）：6 达妙 + 少量外设。
 *   曾设想过 SDK_PROFILE_FULL（RM 全场景 32/16/16）→ **撤销**，因为无第二个真实负载，
 *   双档等于没有定位，且整套常量没有任何用例验证。升级触发条件（三者任一）：
 *   ① 出现非达妙的真实设备 ② 出现第 2 条真实总线需求 ③ 有外部使用者。
 *
 * 【取整规则（D9）】下界可数 → 向上取 2 的幂 → **禁止小数系数**。
 *   早期写成 "22 × 1.45 = 32" / "10 × 1.6 = 16"，是伪精确：看着像推导，实为拍脑袋。
 *
 * 【逐个推导】
 *   SDK_MAX_BUS = 3 …… 硬件事实：板载手册 p5「引出 3 路 CAN」、官方例程 fdcan.h 的 hfdcan1/2/3。
 *                        容量 = 硬件能力；"用几路"由 Bus_Create 调用次数决定（D2）。
 *   SDK_MAX_SUB = 16 … 下界：6 达妙 + 超级电容 1 + IMU 1 + 上位机 1 = 9~10 → 取 2^4 = 16。
 *                        注意"每台电机一条"，不是"每个帧 ID 一条"——方案 A 下 6 轴同 ID 也要 6 条。
 *   SDK_MAX_DEV = 8 … 下界：6 关节 + 1 外设组 + 1 预留 = 8 → 取 2^3。
 *   SDK_MAX_TASK = 8  下界：控制 1 + 下发 1 + 保护巡检 1 + 上报 1 + 遥测 1 = 5
 *                        → 取 2^3 = 8（余量 2 条给临时调试任务）。
 *
 * 【预算校验（证明这些数不构成瓶颈）】
 *   RAM：订阅 16 × 16 B = 256 B/总线；BusStats 40 B → 约 300 B/总线
 *        → 3 路 900 B（H723 1 MB 的 0.09%）。
 *   CPU：每帧遍历整表 = 16 × 5 周期 = 80 周期 ≈ 0.17 µs @480 MHz；
 *        六轴 200 Hz 双向 2400 帧/s → 0.04%。即使 1 kHz 也只有 0.2%。
 *        真正的 CPU 风险在**回调体**与**日志格式化**，不在这里。
 *   ⇒ 结论：不是被 RAM/CPU 卡住，16 以上无用例支撑（YAGNI）。
 *
 * 【为什么不做运行期可配】容量是编译期常量，装错需重烧；所以宁可用例给足、
 *   超限必须返回 NO_RESOURCE（可观测），并在开机 banner 打印占用率（sub=9/16）。
 */
#endif /* SDK_CONFIG_H */
